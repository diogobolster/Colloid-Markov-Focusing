def parse_legacy_vtk(path: Path) -> tuple[np.ndarray, np.ndarray, np.ndarray, np.ndarray]:
    lines = path.read_text(encoding="utf-8", errors="replace").splitlines()
    points: np.ndarray | None = None
    cells: list[np.ndarray] = []
    velocity: np.ndarray | None = None
    i = 0
    while i < len(lines):
        parts = lines[i].strip().split()
        if not parts:
            i += 1
            continue
        key = parts[0].upper()
        if key == "POINTS":
            n_points = int(parts[1])
            values: list[float] = []
            i += 1
            while len(values) < 3 * n_points:
                values.extend(float(v) for v in lines[i].strip().split())
                i += 1
            points = np.asarray(values, dtype=float).reshape(n_points, 3)
            continue
        if key == "CELLS":
            n_cells = int(parts[1])
            n_ints = int(parts[2])
            values_i: list[int] = []
            i += 1
            while len(values_i) < n_ints:
                values_i.extend(int(float(v)) for v in lines[i].strip().split())
                i += 1
            cursor = 0
            for _ in range(n_cells):
                n = values_i[cursor]
                ids = np.asarray(values_i[cursor + 1 : cursor + 1 + n], dtype=int)
                cells.append(ids)
                cursor += n + 1
            continue
        if key == "VECTORS" and len(parts) >= 2 and parts[1] == "U":
            if not cells:
                raise ValueError("Encountered U before CELLS in VTK file")
            n_cells = len(cells)
            values = []
            i += 1
            while len(values) < 3 * n_cells:
                values.extend(float(v) for v in lines[i].strip().split())
                i += 1
            velocity = np.asarray(values, dtype=float).reshape(n_cells, 3)
            continue
        i += 1

    if points is None or velocity is None or not cells:
        raise ValueError(f"Could not parse POINTS/CELLS/VECTORS U from {path}")

    centers = np.empty((len(cells), 3), dtype=float)
    volumes = np.empty(len(cells), dtype=float)
    for c_id, ids in enumerate(cells):
        cell_points = points[ids]
        centers[c_id] = np.mean(cell_points, axis=0)
        area = polygon_area_from_cell_points(cell_points[:, :2])
        thickness = float(np.max(cell_points[:, 2]) - np.min(cell_points[:, 2]))
        volumes[c_id] = area * thickness
    return centers[:, :2], velocity[:, :2], volumes, np.asarray([len(ids) for ids in cells])


def parse_xml_vtu(path: Path) -> tuple[np.ndarray, np.ndarray, np.ndarray, np.ndarray]:
    root = ET.parse(path).getroot()
    piece = root.find(".//Piece")
    if piece is None:
        raise ValueError(f"Could not find Piece element in {path}")

    points_node = piece.find("./Points/DataArray")
    if points_node is None or points_node.text is None:
        raise ValueError(f"Could not find point coordinates in {path}")
    points = np.fromstring(points_node.text, sep=" ", dtype=float).reshape(-1, 3)

    cells_node = piece.find("./Cells")
    if cells_node is None:
        raise ValueError(f"Could not find Cells element in {path}")
    cell_arrays = {node.attrib.get("Name", ""): node for node in cells_node.findall("./DataArray")}
    connectivity = np.fromstring(cell_arrays["connectivity"].text or "", sep=" ", dtype=int)
    offsets = np.fromstring(cell_arrays["offsets"].text or "", sep=" ", dtype=int)

    cell_data = piece.find("./CellData")
    if cell_data is None:
        raise ValueError(f"Could not find CellData element in {path}")
    u_node = None
    for node in cell_data.findall("./DataArray"):
        if node.attrib.get("Name") == "U":
            u_node = node
            break
    if u_node is None or u_node.text is None:
        raise ValueError(f"Could not find cell-centered U in {path}")
    velocity = np.fromstring(u_node.text, sep=" ", dtype=float).reshape(-1, 3)

    n_cells = offsets.size
    centers = np.empty((n_cells, 3), dtype=float)
    volumes = np.empty(n_cells, dtype=float)
    lengths = np.empty(n_cells, dtype=int)
    start = 0
    for c_id, stop in enumerate(offsets):
        ids = connectivity[start:stop]
        cell_points = points[ids]
        centers[c_id] = np.mean(cell_points, axis=0)
        area = polygon_area_from_cell_points(cell_points[:, :2])
        thickness = float(np.max(cell_points[:, 2]) - np.min(cell_points[:, 2]))
        volumes[c_id] = area * thickness
        lengths[c_id] = ids.size
        start = int(stop)
    return centers[:, :2], velocity[:, :2], volumes, lengths


def parse_vtk_field(path: Path) -> tuple[np.ndarray, np.ndarray, np.ndarray, np.ndarray]:
    if path.suffix == ".vtu":
        return parse_xml_vtu(path)
    return parse_legacy_vtk(path)


def polygon_area_from_cell_points(xy: np.ndarray) -> float:
    if xy.size == 0:
        return float("nan")
    rounded = np.unique(np.round(xy, decimals=14), axis=0)
    if rounded.shape[0] < 3:
        return float("nan")
    center = np.mean(rounded, axis=0)
    angles = np.arctan2(rounded[:, 1] - center[1], rounded[:, 0] - center[0])
    ordered = rounded[np.argsort(angles)]
    x = ordered[:, 0]
    y = ordered[:, 1]
    return float(0.5 * abs(np.dot(x, np.roll(y, -1)) - np.dot(y, np.roll(x, -1))))


def find_vtk_file() -> Path:
    vtk_files = sorted((CASE / "VTK").glob("*.vtk"))
    if not vtk_files:
        vtk_files = sorted((CASE / "VTK").glob("*/*.vtk"))

def weighted_mean(values: np.ndarray, weights: np.ndarray) -> float:
    good = np.isfinite(values) & np.isfinite(weights) & (weights > 0)
    if not np.any(good):
        return float("nan")
    return float(np.sum(values[good] * weights[good]) / np.sum(weights[good]))


def weighted_rms(values: np.ndarray, weights: np.ndarray) -> float:
    good = np.isfinite(values) & np.isfinite(weights) & (weights > 0)
    if not np.any(good):
        return float("nan")
    return float(math.sqrt(np.sum(values[good] * values[good] * weights[good]) / np.sum(weights[good])))


def nearest_wall_state(params: PhysicalParams, x: np.ndarray, y: np.ndarray) -> tuple[np.ndarray, np.ndarray, np.ndarray, np.ndarray]:
    rx, ry, r, _, _, collector = _nearest_grain_state(params, x, y)
    theta = np.mod(np.arctan2(ry, rx), 2.0 * np.pi)
    return r - params.grain_radius, theta, r, collector


def compare_fields(params: PhysicalParams, centers: np.ndarray, u_of: np.ndarray, areas: np.ndarray) -> tuple[list[dict[str, float | str]], dict[str, np.ndarray]]:
    flow = load_flow(FLOW_PATH, params=params)
    lbm_ux, lbm_uy = interpolate_velocity(flow, centers[:, 0], centers[:, 1])
    u_lbm = np.column_stack([lbm_ux, lbm_uy])
    diff = u_of - u_lbm
    speed_of = np.linalg.norm(u_of, axis=1)
    speed_lbm = np.linalg.norm(u_lbm, axis=1)
    h_wall, theta, r, collector = nearest_wall_state(params, centers[:, 0], centers[:, 1])

    weights = np.where(np.isfinite(areas) & (areas > 0), areas, np.nanmedian(areas[np.isfinite(areas) & (areas > 0)]))
    dx_lbm = params.cell_length / flow.resolution
    region_masks = {
        "all fluid cells": np.ones(centers.shape[0], dtype=bool),
        f"bulk, h > {2.0 * dx_lbm * 1e6:.2f} um": h_wall > 2.0 * dx_lbm,
        f"near wall, h <= {2.0 * dx_lbm * 1e6:.2f} um": h_wall <= 2.0 * dx_lbm,
    }
    rows: list[dict[str, float | str]] = []
    ubar = params.mean_velocity
    for region, mask in region_masks.items():
        w = np.where(mask, weights, np.nan)
        rms_abs = weighted_rms(np.linalg.norm(diff, axis=1), w)
        rms_lbm = weighted_rms(speed_lbm, w)
        mean_abs = weighted_mean(np.linalg.norm(diff, axis=1), w)
        ux_corr = np.corrcoef(u_of[mask, 0], u_lbm[mask, 0])[0, 1] if int(np.sum(mask)) > 3 else float("nan")
        rows.append(
            {
                "region": region,
                "cells": int(np.sum(mask)),
                "area_fraction": weighted_mean(mask.astype(float), weights),
                "mean_abs_error_over_U": mean_abs / ubar,
                "rms_vector_error_over_U": rms_abs / ubar,
                "rms_error_over_lbm_rms_speed": rms_abs / rms_lbm if rms_lbm > 0 else float("nan"),
                "ux_correlation": float(ux_corr),
                "mean_of_ux_m_s": weighted_mean(u_of[:, 0], w),
                "mean_lbm_ux_m_s": weighted_mean(u_lbm[:, 0], w),
            }
        )
    arrays = {
        "centers": centers,
        "u_of": u_of,
        "u_lbm": u_lbm,
        "areas": weights,
        "speed_of": speed_of,
        "speed_lbm": speed_lbm,
        "error": np.linalg.norm(diff, axis=1),
        "h_wall": h_wall,
        "theta": theta,
        "collector": collector,
    }
    return rows, arrays


def ring_summary(params: PhysicalParams, arrays: dict[str, np.ndarray]) -> list[dict[str, float | str]]:
    centers = arrays["centers"]
    u_of = arrays["u_of"]
    u_lbm = arrays["u_lbm"]
    weights = arrays["areas"]
    well = secondary_minimum_well(
        replace(params, ionic_strength_molar=50.0e-3, zeta_collector_unfavorable=-50.0e-3),
        "unfavorable",
    )
    gaps = [
        ("particle center, 10 nm surface gap", 10.0e-9),
        ("particle center, 200 nm surface gap", 200.0e-9),
    ]
    if bool(well["has_well"]):
        gaps.insert(1, ("particle center, 50 mM zeta -50 well", float(well["minimum_gap"])))
    rows: list[dict[str, float | str]] = []
    for collector_name, collector_id in (("corner", 0), ("center", 1)):
        if collector_name == "center":
            cx = 0.5 * params.cell_length
            cy = 0.5 * params.cell_length
        else:
            cx = 0.0
            cy = 0.0
        dx = centers[:, 0] - cx
        dy = centers[:, 1] - cy
        if collector_name == "corner":
            dx = ((dx + 0.5 * params.cell_length) % params.cell_length) - 0.5 * params.cell_length
            dy = ((dy + 0.5 * params.cell_length) % params.cell_length) - 0.5 * params.cell_length
        radius = np.sqrt(dx * dx + dy * dy)
        theta = np.mod(np.arctan2(dy, dx), 2.0 * np.pi)
        tx = -np.sin(theta)
        ty = np.cos(theta)
        ut_of = u_of[:, 0] * tx + u_of[:, 1] * ty
        ut_lbm = u_lbm[:, 0] * tx + u_lbm[:, 1] * ty
        for label, gap in gaps:
            target_radius = params.grain_radius + params.particle_radius + gap
            shell_half_width = 1.5e-6
            mask = np.abs(radius - target_radius) <= shell_half_width
            if collector_name == "center":
                mask &= arrays["collector"] == collector_id
            else:
                mask &= arrays["collector"] == collector_id
            w = np.where(mask, weights, np.nan)
            rows.append(
                {
                    "collector": collector_name,
                    "sample": label,
                    "target_wall_distance_um": (params.particle_radius + gap) * 1.0e6,
                    "shell_half_width_um": shell_half_width * 1.0e6,
                    "cells": int(np.sum(mask)),
                    "median_abs_ut_openfoam_um_s": float(np.nanmedian(np.abs(ut_of[mask])) * 1.0e6) if np.any(mask) else float("nan"),
                    "median_abs_ut_lbm_um_s": float(np.nanmedian(np.abs(ut_lbm[mask])) * 1.0e6) if np.any(mask) else float("nan"),
                    "p95_abs_ut_openfoam_um_s": float(np.nanquantile(np.abs(ut_of[mask]), 0.95) * 1.0e6) if np.any(mask) else float("nan"),
                    "p95_abs_ut_lbm_um_s": float(np.nanquantile(np.abs(ut_lbm[mask]), 0.95) * 1.0e6) if np.any(mask) else float("nan"),
                    "weighted_mean_abs_ut_error_um_s": weighted_mean(np.abs(ut_of - ut_lbm), w) * 1.0e6,
                }
            )
    return rows


def binned_center_ring_profile(params: PhysicalParams, arrays: dict[str, np.ndarray]) -> dict[str, np.ndarray]:
    well = secondary_minimum_well(
        replace(params, ionic_strength_molar=50.0e-3, zeta_collector_unfavorable=-50.0e-3),
        "unfavorable",
    )
    gap = float(well["minimum_gap"]) if bool(well["has_well"]) else 10.0e-9
    centers = arrays["centers"]
    dx = centers[:, 0] - 0.5 * params.cell_length
    dy = centers[:, 1] - 0.5 * params.cell_length
    radius = np.sqrt(dx * dx + dy * dy)
    theta = np.mod(np.arctan2(dy, dx), 2.0 * np.pi)
    target_radius = params.grain_radius + params.particle_radius + gap
    shell_half_width = 1.5e-6
    mask = (arrays["collector"] == 1) & (np.abs(radius - target_radius) <= shell_half_width)
    tx = -np.sin(theta)
    ty = np.cos(theta)
    ut_of = arrays["u_of"][:, 0] * tx + arrays["u_of"][:, 1] * ty
    ut_lbm = arrays["u_lbm"][:, 0] * tx + arrays["u_lbm"][:, 1] * ty
    bins = np.linspace(0.0, 2.0 * np.pi, 49)
    centers_theta = 0.5 * (bins[:-1] + bins[1:])
    of_mean = np.full(centers_theta.shape, np.nan)
    lbm_mean = np.full(centers_theta.shape, np.nan)
    counts = np.zeros(centers_theta.shape, dtype=int)
    for i in range(centers_theta.size):
        in_bin = mask & (theta >= bins[i]) & (theta < bins[i + 1])
        counts[i] = int(np.sum(in_bin))
        if counts[i] > 0:
            of_mean[i] = float(np.mean(ut_of[in_bin]))
            lbm_mean[i] = float(np.mean(ut_lbm[in_bin]))
    return {
        "theta": centers_theta,
        "openfoam": of_mean,
        "lbm": lbm_mean,
        "counts": counts,
        "gap": np.asarray([gap]),
    }


def write_csv(path: Path, rows: list[dict[str, float | int | str]]) -> None:
    if not rows:
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        writer.writeheader()
        writer.writerows(rows)


def extract_log_summary() -> dict[str, str]:
    summary: dict[str, str] = {}
    for name in ("log.blockMesh", "log.snappyHexMesh", "log.checkMesh", "log.simpleFoam"):
        path = OUT / name
        text = path.read_text(encoding="utf-8", errors="replace") if path.exists() else ""
        summary[name] = "\n".join(text.splitlines()[-12:])
    return summary


def create_figure(params: PhysicalParams, arrays: dict[str, np.ndarray], comparison_rows: list[dict[str, float | str]]) -> None:
    import matplotlib.pyplot as plt

    FIGURES.mkdir(parents=True, exist_ok=True)
    flow = load_flow(FLOW_PATH, params=params)
    speed = np.sqrt(flow.ux**2 + flow.uy**2) * 1.0e6
    masked = np.ma.masked_where(flow.solid, speed)
    centers = arrays["centers"]
    speed_of = arrays["speed_of"] * 1.0e6
    error = arrays["error"] / params.mean_velocity
    profile = binned_center_ring_profile(params, arrays)

    fig, axes = plt.subplots(2, 2, figsize=(10.5, 8.0), constrained_layout=True)
    cmap = "turbo"
    ax = axes[0, 0]
    im = ax.imshow(
        masked.T,
        origin="lower",
        extent=(0, params.cell_length * 1e6, 0, params.cell_length * 1e6),
        cmap=cmap,
    )
    ax.set_title("LBM speed, N=192")
    ax.set_aspect("equal")
    ax.set_xlabel("x (um)")
    ax.set_ylabel("y (um)")
    fig.colorbar(im, ax=ax, label="speed (um/s)")

    ax = axes[0, 1]
    sc = ax.scatter(centers[:, 0] * 1e6, centers[:, 1] * 1e6, c=speed_of, s=2, cmap=cmap, linewidths=0)
    ax.set_title("OpenFOAM speed")
    ax.set_aspect("equal")
    ax.set_xlabel("x (um)")
    ax.set_ylabel("y (um)")
    fig.colorbar(sc, ax=ax, label="speed (um/s)")

    ax = axes[1, 0]
    sc2 = ax.scatter(centers[:, 0] * 1e6, centers[:, 1] * 1e6, c=np.clip(error, 0, 1.2), s=2, cmap="magma", linewidths=0)
    ax.set_title("|OpenFOAM - LBM| / Ubar")
    ax.set_aspect("equal")
    ax.set_xlabel("x (um)")
    ax.set_ylabel("y (um)")
    fig.colorbar(sc2, ax=ax, label="normalized error")

    ax = axes[1, 1]
    theta_deg = np.degrees(profile["theta"])
    ax.plot(theta_deg, profile["openfoam"] * 1.0e6, color="#1f77b4", lw=2.0, label="OpenFOAM")
    ax.plot(theta_deg, profile["lbm"] * 1.0e6, color="#d62728", lw=2.0, label="LBM")
    ax.axhline(0, color="0.25", lw=0.8)
    ax.set_title(f"Center-grain tangential velocity, gap={float(profile['gap'][0]) * 1e9:.1f} nm")
    ax.set_xlabel("angle from downstream stagnation point (deg)")
    ax.set_ylabel("u_t (um/s)")
    ax.set_xlim(0, 360)
    ax.legend(frameon=False)

    for ax in axes.ravel()[:3]:
        for cx, cy in ((0.5, 0.5), (0, 0), (1, 0), (0, 1), (1, 1)):
            circ = plt.Circle(
                (cx * params.cell_length * 1e6, cy * params.cell_length * 1e6),
                params.grain_radius * 1e6,
                facecolor="black",
                edgecolor="black",
                lw=0.8,
            )
            ax.add_patch(circ)
        ax.set_xlim(0, params.cell_length * 1e6)
        ax.set_ylim(0, params.cell_length * 1e6)

    fig.suptitle("Body-fitted OpenFOAM benchmark of periodic center/corner-grain LBM flow", fontsize=14)
    fig.savefig(FIGURES / "fig18_openfoam_lbm_benchmark.png", dpi=220)
    plt.close(fig)


def write_report(
    params: PhysicalParams,
    comparison_rows: list[dict[str, float | str]],
    ring_rows: list[dict[str, float | str]],
    arrays: dict[str, np.ndarray],
    vtk_path: Path,
) -> None:
    true_porosity = 1.0 - 2.0 * math.pi * params.grain_radius**2 / params.cell_length**2
    mesh_porosity = float(np.nansum(arrays["areas"]) / (params.cell_length**2 * (2.0 * Z_HALF)))
    flow = load_flow(FLOW_PATH, params=params)
    lbm_porosity = float(np.mean(~flow.solid))
    logs = extract_log_summary()

    def fmt(x: object, digits: int = 4) -> str:
        if isinstance(x, (int, np.integer)):
            return str(int(x))
        try:
            val = float(x)
        except (TypeError, ValueError):
            return str(x)
        if not np.isfinite(val):
            return "nan"
        return f"{val:.{digits}g}"

    lines: list[str] = [
        "# OpenFOAM/LBM periodic-cell flow benchmark",
        "",
        "The benchmark solves the same center/corner-grain periodic cell used by the particle tracker with a body-fitted OpenFOAM mesh.",
        f"The cell length is {params.cell_length:.3e} m, the grain radius is {params.grain_radius:.3e} m, and the imposed volume-mean velocity is {params.mean_velocity:.6e} m/s ({TARGET_M_PER_DAY:.1f} m/day).",
        f"The OpenFOAM case uses `snappyHexMesh` on a {BASE_CELLS} x {BASE_CELLS} x {Z_CELLS} thin-slab base mesh with surface refinement level {SURFACE_REFINEMENT}, `cyclicAMI` boundaries on both periodic directions, symmetry front/back planes, no-slip grain boundaries, laminar `simpleFoam`, and `meanVelocityForce`.",
        f"The Reynolds number based on grain diameter and water viscosity is {params.reynolds_number:.3g}, so the solved Navier-Stokes problem is in the creeping-flow regime for this benchmark.",
        f"The exported VTK field was parsed from `{vtk_path}`.",
        "",
        "## Porosity",
        "",
        "| quantity | value |",
        "| --- | ---: |",
        f"| analytic center+corner cell | {true_porosity:.6f} |",
        f"| LBM solid mask, N=192 | {lbm_porosity:.6f} |",
        f"| OpenFOAM body-fitted mesh | {mesh_porosity:.6f} |",
        "",
        "## Field comparison sampled on OpenFOAM cell centers",
        "",
        "| region | cells | area frac | mean abs err/U | rms vector err/U | rms err/LBM rms speed | ux corr | mean OpenFOAM ux | mean LBM ux |",
        "| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |",
    ]
    for row in comparison_rows:
        lines.append(
            "| "
            + " | ".join(
                [
                    str(row["region"]),
                    fmt(row["cells"], 0),
                    fmt(row["area_fraction"], 4),
                    fmt(row["mean_abs_error_over_U"], 4),
                    fmt(row["rms_vector_error_over_U"], 4),
                    fmt(row["rms_error_over_lbm_rms_speed"], 4),
                    fmt(row["ux_correlation"], 4),
                    fmt(row["mean_of_ux_m_s"], 6),
                    fmt(row["mean_lbm_ux_m_s"], 6),
                ]
            )
            + " |"
        )

    lines.extend(
        [
            "",
            "## Near-wall tangential velocity shells",
            "",
            "| collector | sample | cells | target wall distance (um) | median |ut| OF (um/s) | median |ut| LBM (um/s) | p95 |ut| OF (um/s) | p95 |ut| LBM (um/s) | mean |ut err| (um/s) |",
            "| --- | --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: |",
        ]
    )
    for row in ring_rows:
        lines.append(
            "| "
            + " | ".join(
                [
                    str(row["collector"]),
                    str(row["sample"]),
                    fmt(row["cells"], 0),
                    fmt(row["target_wall_distance_um"], 4),
                    fmt(row["median_abs_ut_openfoam_um_s"], 4),
                    fmt(row["median_abs_ut_lbm_um_s"], 4),
                    fmt(row["p95_abs_ut_openfoam_um_s"], 4),
                    fmt(row["p95_abs_ut_lbm_um_s"], 4),
                    fmt(row["weighted_mean_abs_ut_error_um_s"], 4),
                ]
            )
            + " |"
        )
    lines.extend(
        [
            "",
            "## Interpretation",
            "",
            "This is a direct velocity benchmark, not a particle-tracking run. The useful reading is the split between bulk and near-wall error: bulk agreement tests the periodic forcing and pore-scale flow topology, while near-wall error captures the expected difference between a stair-step bounce-back LBM boundary and a body-fitted circular collector.",
            "The current particle tracker still uses the LBM field; this benchmark establishes whether that is defensible for the focusing calculations or whether the next refinement should replace or correct the near-wall flow interpolation.",
            "",
            "## Log tails",
            "",
        ]
    )
    for name, tail in logs.items():
        lines.append(f"### {name}")
        lines.append("")
        lines.append("```")
        lines.append(tail)
        lines.append("```")
        lines.append("")
    (OUT / "openfoam_lbm_benchmark_report.md").write_text("\n".join(lines), encoding="utf-8")


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    FIGURES.mkdir(parents=True, exist_ok=True)
    params = PhysicalParams(mean_velocity=TARGET_M_PER_DAY / 86400.0)
    reuse = "--reuse" in sys.argv
    if not reuse:
        write_case(params)
        run_openfoam_case()
    vtk_path = find_vtk_file()
    centers, u_of, areas, _ = parse_vtk_field(vtk_path)
    comparison_rows, arrays = compare_fields(params, centers, u_of, areas)
    ring_rows = ring_summary(params, arrays)
    write_csv(OUT / "openfoam_lbm_field_comparison.csv", comparison_rows)
    write_csv(OUT / "openfoam_lbm_tangential_shells.csv", ring_rows)
    np.savez_compressed(
        OUT / "openfoam_lbm_sampled_fields.npz",
        **arrays,
    )
    create_figure(params, arrays, comparison_rows)
    write_report(params, comparison_rows, ring_rows, arrays, vtk_path)
    print(f"Wrote benchmark report to {OUT / 'openfoam_lbm_benchmark_report.md'}")
    print(f"Wrote figure to {FIGURES / 'fig18_openfoam_lbm_benchmark.png'}")


if __name__ == "__main__":
    main()

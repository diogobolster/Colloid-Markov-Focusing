def foam_header(class_name: str, location: str, object_name: str) -> str:
    return textwrap.dedent(
        f"""\
        /*--------------------------------*- C++ -*----------------------------------*\\
        | OpenFOAM dictionary generated by scripts/run_random_openfoam_flow.py       |
        \\*---------------------------------------------------------------------------*/
        FoamFile
        {{
            version     2.0;
            format      ascii;
            class       {class_name};
            location    "{location}";
            object      {object_name};
        }}
        // ************************************************************************* //

        """
    )


def write_foam_file(path: Path, class_name: str, location: str, object_name: str, body: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(foam_header(class_name, location, object_name) + textwrap.dedent(body), encoding="utf-8")


def run(cmd: list[str], cwd: Path, log_name: str) -> None:
    log_path = OUT / log_name
    with log_path.open("w", encoding="utf-8") as log:
        log.write("$ " + " ".join(cmd) + "\n\n")
        log.flush()
        completed = subprocess.run(
            cmd,
            cwd=cwd,
            stdout=log,
            stderr=subprocess.STDOUT,
            text=True,
            check=False,
        )
    if completed.returncode != 0:
        tail = "\n".join(log_path.read_text(encoding="utf-8", errors="replace").splitlines()[-100:])
        raise RuntimeError(f"{cmd[0]} failed with code {completed.returncode}; tail of {log_path}:\n{tail}")



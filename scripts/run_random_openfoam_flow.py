def polygon_area_from_cell_points(xy: np.ndarray) -> float:
    rounded = np.unique(np.round(xy, decimals=14), axis=0)
    if rounded.shape[0] < 3:
        return float("nan")
    center = np.mean(rounded, axis=0)
    angles = np.arctan2(rounded[:, 1] - center[1], rounded[:, 0] - center[0])
    ordered = rounded[np.argsort(angles)]
    x = ordered[:, 0]
    y = ordered[:, 1]
    return float(0.5 * abs(np.dot(x, np.roll(y, -1)) - np.dot(y, np.roll(x, -1))))


def parse_xml_vtu(path: Path) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    root = ET.parse(path).getroot()
    piece = root.find(".//Piece")
    if piece is None:
        raise ValueError(f"Could not find Piece element in {path}")

    points_node = piece.find("./Points/DataArray")
    if points_node is None or points_node.text is None:
        raise ValueError(f"Could not find point coordinates in {path}")
    points = np.fromstring(points_node.text, sep=" ", dtype=float).reshape(-1, 3)

    cells_node = piece.find("./Cells")
    if cells_node is None:
        raise ValueError(f"Could not find Cells element in {path}")
    cell_arrays = {node.attrib.get("Name", ""): node for node in cells_node.findall("./DataArray")}
    connectivity = np.fromstring(cell_arrays["connectivity"].text or "", sep=" ", dtype=int)
    offsets = np.fromstring(cell_arrays["offsets"].text or "", sep=" ", dtype=int)

    cell_data = piece.find("./CellData")
    if cell_data is None:
        raise ValueError(f"Could not find CellData in {path}")
    u_node = None
    for node in cell_data.findall("./DataArray"):
        if node.attrib.get("Name") == "U":
            u_node = node
            break
    if u_node is None or u_node.text is None:
        raise ValueError(f"Could not find cell-centered U in {path}")
    velocity = np.fromstring(u_node.text, sep=" ", dtype=float).reshape(-1, 3)

    n_cells = offsets.size
    centers = np.empty((n_cells, 3), dtype=float)
    areas = np.empty(n_cells, dtype=float)
    start = 0
    for c_id, stop in enumerate(offsets):
        ids = connectivity[start:stop]
        cell_points = points[ids]
        centers[c_id] = np.mean(cell_points, axis=0)
        areas[c_id] = polygon_area_from_cell_points(cell_points[:, :2])
        start = int(stop)
    return centers[:, :2], velocity[:, :2], areas


def find_vtu_file() -> Path:
    candidates = sorted((CASE / "VTK").glob("*/*.vtu"))
    internal = [p for p in candidates if p.name == "internal.vtu"]
    if internal:
        return internal[-1]
    if candidates:
        return candidates[-1]
    raise FileNotFoundError(f"No VTU files found under {CASE / 'VTK'}")


def read_log_tail(name: str, n: int = 30) -> str:
    path = OUT / name
    if not path.exists():
        return ""
    return "\n".join(path.read_text(encoding="utf-8", errors="replace").splitlines()[-n:])


def draw_flow_figure(geometry: dict, centers_xy: np.ndarray, velocity_xy: np.ndarray, areas: np.ndarray) -> dict:
    lx = float(geometry["domain"]["length_x"])
    ly = float(geometry["domain"]["length_y"])
    grains = geometry["grains"]
    centers = np.array([[g["x"], g["y"]] for g in grains], dtype=float)
    radii = np.array([g["radius"] for g in grains], dtype=float)
    pinned = np.array([bool(g.get("pinned", False)) for g in grains], dtype=bool)

    speed = np.linalg.norm(velocity_xy, axis=1)
    good = np.isfinite(speed) & np.isfinite(areas) & (areas > 0)
    mean_ux = float(np.sum(velocity_xy[good, 0] * areas[good]) / np.sum(areas[good]))
    mean_uy = float(np.sum(velocity_xy[good, 1] * areas[good]) / np.sum(areas[good]))
    mean_speed = float(np.sum(speed[good] * areas[good]) / np.sum(areas[good]))
    max_speed = float(np.nanmax(speed))

    fig, axes = plt.subplots(1, 2, figsize=(13.5, 5.2), dpi=180)
    ax = axes[0]
    triang = ax.tricontourf(
        centers_xy[:, 0],
        centers_xy[:, 1],
        speed / max(UBAR, 1.0e-30),
        levels=40,
        cmap="turbo",
    )
    fig.colorbar(triang, ax=ax, fraction=0.046, pad=0.02, label=r"$|\mathbf{u}|/\bar{u}$")
    for gid, ((cx, cy), radius) in enumerate(zip(centers, radii)):
        edge = "#f97316" if pinned[gid] else "#020617"
        lw = 1.6 if pinned[gid] else 0.5
        ax.add_patch(Circle((cx, cy), radius, fc="#111827", ec=edge, lw=lw))
    ax.set_title("OpenFOAM speed field")

    ax = axes[1]
    ax.add_patch(Rectangle((0.0, 0.0), lx, ly, fill=False, lw=1.5, ec="#111827"))
    for gid, ((cx, cy), radius) in enumerate(zip(centers, radii)):
        edge = "#f97316" if pinned[gid] else "#020617"
        lw = 1.6 if pinned[gid] else 0.5
        ax.add_patch(Circle((cx, cy), radius, fc="#111827", ec=edge, lw=lw))
        ax.text(cx, cy, str(gid), color="white", fontsize=5.0, ha="center", va="center")
    rng = np.random.default_rng(22)
    if centers_xy.shape[0] > 1800:
        sample = rng.choice(centers_xy.shape[0], size=1800, replace=False)
    else:
        sample = np.arange(centers_xy.shape[0])
    ax.quiver(
        centers_xy[sample, 0],
        centers_xy[sample, 1],
        velocity_xy[sample, 0],
        velocity_xy[sample, 1],
        speed[sample],
        cmap="viridis",
        width=0.0015,
        scale=max_speed * 60.0,
        minlength=0.0,
        alpha=0.85,
    )
    ax.set_title("Cell-centered velocity vectors")

    for ax in axes:
        ax.set_aspect("equal", adjustable="box")
        ax.set_xlim(0.0, lx)
        ax.set_ylim(0.0, ly)
        ax.set_xlabel("x (m)")
    axes[0].set_ylabel("y (m)")
    fig.tight_layout()
    fig.savefig(OUT / "random_openfoam_flow.png")
    plt.close(fig)

    return {
        "cells": int(centers_xy.shape[0]),
        "area_sum": float(np.sum(areas[good])),
        "mean_ux": mean_ux,
        "mean_uy": mean_uy,
        "mean_speed": mean_speed,
        "max_speed": max_speed,
        "target_ux": UBAR,
        "mean_ux_over_target": mean_ux / UBAR,
        "max_speed_over_target": max_speed / UBAR,
    }



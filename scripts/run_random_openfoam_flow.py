def write_force_options() -> None:
    if FORCING_MODE == "body_force":
        # Specific vector source in the momentum equation. This avoids the
        # meanVelocityForce feedback division that is brittle for imperfect AMI
        # screens; Stokes linearity lets downstream analyses rescale velocities.
        body = f"""
        bodyForce1
        {{
            type            vectorSemiImplicitSource;
            active          yes;
            selectionMode   all;
            volumeMode      specific;
            sources
            {{
                U           (({BODY_ACCEL:.12g} 0 0) 0);
            }}
        }}
        """
    else:
        body = f"""
        meanVelocityForce1
        {{
            type            meanVelocityForce;
            active          yes;
            selectionMode   all;
            Ubar            ({UBAR:.12g} 0 0);
            fields          (U);
            relaxation      1.0;
        }}
        """
    write_foam_file(
        CASE / "constant" / "fvOptions",
        "dictionary",
        "constant",
        "fvOptions",
        body,
    )


def remove_solution_times() -> None:
    if not CASE.exists():
        return
    for path in CASE.iterdir():
        if not path.is_dir() or path.name == "0":
            continue
        try:
            float(path.name)
        except ValueError:
            continue
        shutil.rmtree(path)


